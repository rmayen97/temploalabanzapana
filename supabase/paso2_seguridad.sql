-- ¿La contraseña es correcta? (para desbloquear la interfaz de admin)
create or replace function public.es_admin(p_pass text)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  perform privado.verificar_admin(p_pass);
  return true;
exception when sqlstate '28P01' then
  return false;
end $$;

-- Voluntario completa SU perfil (solo si aún no estaba completo)
create or replace function public.completar_perfil(p_id bigint, p_email text, p_fecha date)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if p_email is null or p_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' or p_fecha is null then
    raise exception 'Datos inválidos';
  end if;
  update public.colaboradores
     set email = p_email, fecha_nacimiento = p_fecha
   where id = p_id
     and (email is null or email = '' or fecha_nacimiento is null);
end $$;

-- Admin: ver emails y fechas de nacimiento
create or replace function public.admin_listar_perfiles(p_pass text)
returns table (id bigint, email text, fecha_nacimiento date)
language plpgsql security definer set search_path = '' as $$
begin
  perform privado.verificar_admin(p_pass);
  return query select c.id::bigint, c.email::text, c.fecha_nacimiento::date from public.colaboradores c;
end $$;

-- Admin: editar email / fecha de nacimiento de cualquiera
create or replace function public.admin_guardar_perfil(p_pass text, p_id bigint, p_email text, p_fecha date)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform privado.verificar_admin(p_pass);
  update public.colaboradores
     set email = nullif(p_email, ''), fecha_nacimiento = p_fecha
   where id = p_id;
end $$;

-- Admin: crear turno
create or replace function public.admin_crear_turno(p_pass text, p_fecha date, p_turno text, p_colaborador_id bigint, p_rol text, p_notas text)
returns setof public.turnos language plpgsql security definer set search_path = '' as $$
begin
  perform privado.verificar_admin(p_pass);
  return query
    insert into public.turnos (fecha, turno, colaborador_id, rol, notas)
    values (p_fecha, upper(p_turno), p_colaborador_id, coalesce(p_rol, ''), coalesce(p_notas, ''))
    returning *;
end $$;

-- Admin: editar turno (solo cambia los campos que se envían)
create or replace function public.admin_actualizar_turno(p_pass text, p_id bigint, p_cambios jsonb)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform privado.verificar_admin(p_pass);
  update public.turnos set
    fecha          = coalesce((p_cambios->>'fecha')::date, fecha),
    turno          = coalesce(upper(p_cambios->>'turno'), turno),
    colaborador_id = coalesce((p_cambios->>'colaborador_id')::bigint, colaborador_id),
    rol            = case when p_cambios ? 'rol'   then coalesce(p_cambios->>'rol', '')   else rol   end,
    notas          = case when p_cambios ? 'notas' then coalesce(p_cambios->>'notas', '') else notas end
  where id = p_id;
end $$;

-- Admin: borrar turno
create or replace function public.admin_borrar_turno(p_pass text, p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform privado.verificar_admin(p_pass);
  delete from public.turnos where id = p_id;
end $$;

-- Admin: aprobar / rechazar ausencia
create or replace function public.admin_estado_ausencia(p_pass text, p_id bigint, p_estado text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform privado.verificar_admin(p_pass);
  if p_estado not in ('Pendiente', 'Aprobada', 'Rechazada') then
    raise exception 'Estado inválido';
  end if;
  update public.ausencias set estado = p_estado where id = p_id;
end $$;

-- Admin: borrar ausencia
create or replace function public.admin_borrar_ausencia(p_pass text, p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform privado.verificar_admin(p_pass);
  delete from public.ausencias where id = p_id;
end $$;

-- Quién puede llamar cada función
revoke all on function privado.verificar_admin(text) from public, anon, authenticated;
grant execute on function
  public.es_admin(text),
  public.completar_perfil(bigint, text, date),
  public.admin_listar_perfiles(text),
  public.admin_guardar_perfil(text, bigint, text, date),
  public.admin_crear_turno(text, date, text, bigint, text, text),
  public.admin_actualizar_turno(text, bigint, jsonb),
  public.admin_borrar_turno(text, bigint),
  public.admin_estado_ausencia(text, bigint, text),
  public.admin_borrar_ausencia(text, bigint)
to anon, authenticated;

