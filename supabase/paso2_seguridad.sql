create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------
-- 1. Contraseña de admin: se guarda CIFRADA en un esquema privado
--    (la API pública no puede ver el esquema "privado").
-- ---------------------------------------------------------------------
create schema if not exists privado;
revoke all on schema privado from public, anon, authenticated;

create table if not exists privado.admin_secret (
  id   int primary key default 1 check (id = 1),
  hash text not null
);

-- Copia la contraseña actual (la que pusiste en el paso 1) ya cifrada,
-- y borra la versión en texto plano de public.config.
do $$
declare v text;
begin
  select value into v from public.config where key = 'admin_password';
  if v is not null and v <> '' then
    insert into privado.admin_secret (id, hash)
    values (1, extensions.crypt(v, extensions.gen_salt('bf')))
    on conflict (id) do update set hash = excluded.hash;
    delete from public.config where key = 'admin_password';
  end if;
end $$;

-- Para cambiar la contraseña en el futuro:
--   update privado.admin_secret set hash = extensions.crypt('NUEVA', extensions.gen_salt('bf')) where id = 1;

create or replace function privado.verificar_admin(p_pass text)
returns void language plpgsql security definer set search_path = '' as $$
declare ok boolean;
begin
  select exists (
    select 1 from privado.admin_secret
    where hash = extensions.crypt(coalesce(p_pass, ''), hash)
  ) into ok;
  if not ok then
    perform pg_sleep(1);  -- frena intentos de adivinar
    raise exception 'Contraseña incorrecta' using errcode = '28P01';
  end if;
end $$;

