-- ---------------------------------------------------------------------
-- 3. Activar RLS (reglas de acceso) en todas las tablas
-- ---------------------------------------------------------------------
alter table public.config         enable row level security;
alter table public.colaboradores  enable row level security;
alter table public.turnos         enable row level security;
alter table public.ausencias      enable row level security;
alter table public.canciones      enable row level security;
alter table public.contenido      enable row level security;

-- Borra políticas anteriores para empezar limpio
do $$
declare r record;
begin
  for r in select schemaname, tablename, policyname from pg_policies
           where schemaname = 'public'
             and tablename in ('config','colaboradores','turnos','ausencias','canciones','contenido')
  loop
    execute format('drop policy %I on %I.%I', r.policyname, r.schemaname, r.tablename);
  end loop;
end $$;

-- config: nadie desde la web (sin políticas = sin acceso)
revoke all on public.config from anon, authenticated;

-- colaboradores: la tabla queda cerrada; se lee por la vista pública (sin email ni fecha)
revoke all on public.colaboradores from anon, authenticated;

create or replace view public.colaboradores_publico
with (security_invoker = false) as
select id, nombre, roles, color,
       (email is not null and email <> '' and fecha_nacimiento is not null) as perfil_completo
from public.colaboradores;
grant select on public.colaboradores_publico to anon, authenticated;

-- turnos: todos leen; escribir solo vía funciones admin
create policy turnos_leer on public.turnos for select to anon, authenticated using (true);
revoke insert, update, delete on public.turnos from anon, authenticated;
grant select on public.turnos to anon, authenticated;

-- ausencias: todos leen; cualquiera puede CREAR una, pero solo en estado Pendiente
create policy ausencias_leer  on public.ausencias for select to anon, authenticated using (true);
create policy ausencias_crear on public.ausencias for insert to anon, authenticated
  with check (estado = 'Pendiente');
revoke update, delete on public.ausencias from anon, authenticated;
grant select, insert on public.ausencias to anon, authenticated;

-- canciones y contenido: abiertos para todos (decisión del equipo)
create policy canciones_todo on public.canciones for all to anon, authenticated using (true) with check (true);
create policy contenido_todo on public.contenido for all to anon, authenticated using (true) with check (true);
grant select, insert, update, delete on public.canciones, public.contenido to anon, authenticated;

